"""results_spot.json -> RESULTS.md."""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))

LABEL = {"elome64": "Elómë, float64 (CPU)", "elome32": "Elómë, float32 (GPU kernels)",
         "jaxoplanet": "jaxoplanet starry, ydeg {}", "spotter": "spotter, nside {} ({:,} pixels)"}


def label(key):
    code, _, res = key.partition(":")
    if code == "spotter":
        n = int(res)
        return LABEL[code].format(n, 12 * n * n)
    return LABEL[code].format(res) if res else LABEL[code]


def ppm(v):
    v *= 1e6
    return f"{v:.2g}" if v < 100 else f"{v:,.0f}"


def seconds(v):
    return f"{v * 1e3:,.1f} ms" if v < 1 else f"{v:,.1f} s" if v < 60 else f"{v / 60:,.1f} min"


def main():
    with open(os.path.join(HERE, "results_spot.json")) as f:
        res = json.load(f)
    out = ["# Spot crossings: cross-code results", "",
           "Generated by `make_report_spot.py` from `results_spot.json`; see "
           "[README.md](README.md) for the scenario, the mappings and how to "
           "run it.", ""]
    prec = res.get("precision", {})
    if prec:
        cases = list(prec)
        out += ["## Precision", "",
                "Largest error in the relative flux over the crossing (ppm), against "
                "the brute-force spot integral (`tests/spot_oracle.py`). The last row "
                "is the spots' own signal: the oracle with and without them.", "",
                "| code | " + " | ".join(cases) + " |",
                "|---|" + "---:|" * len(cases)]
        keys = [k for k in prec[cases[0]] if k != "spot_signal"]
        for k in keys:
            out.append(f"| {label(k)} | " + " | ".join(
                ppm(prec[c][k]["max"]) if k in prec[c] else "--" for c in cases) + " |")
        out.append("| *the spots' signal* | " + " | ".join(
            ppm(prec[c]["spot_signal"]) for c in cases) + " |")
        out.append("")
    sp = res.get("speed", {})
    if sp:
        out += ["## Speed", "",
                "One light curve of 1,000 points across the `chord` case: the warm "
                "time (median of repeated calls) and the first call, compilation "
                "included. Value + gradient: in the planet's radius and every "
                "spot's longitude, latitude, radius and contrast.", "",
                "| code | value | value + grad | first call (value) | first call (value + grad) |",
                "|---|---:|---:|---:|---:|"]
        for k, m in sp.items():
            def cell(mode, field):
                v = m.get(mode, {}).get(field)
                return "--" if v is None else seconds(v)
            out.append(f"| {label(k)} | {cell('time', 'warm_s')} | {cell('time_grad', 'warm_s')} | "
                       f"{cell('time', 'first_s')} | {cell('time_grad', 'first_s')} |")
        out += ["",
                "JAX runs on the CPU (it has no Metal backend here), in float64. The "
                "first call is each code's cost before its first light curve: JAX's "
                "tracing and compilation, which grows steeply with jaxoplanet's "
                "`ydeg`; MLX's graph and Metal kernel compilation for Elómë. Each "
                "process starts cold, but macOS keeps compiled Metal shaders between "
                "processes, so a repeat of Elómë's float32 first call takes about "
                "30 ms; its float64 first call varies between about 1.7 s and 4 s.",
                ""]
    mach = res.get("machine", {})
    if mach:
        out += [f"Machine: {mach.get('platform')}, Python {mach.get('python')}.", ""]
    with open(os.path.join(HERE, "RESULTS.md"), "w") as f:
        f.write("\n".join(out))
    print("wrote RESULTS.md")


if __name__ == "__main__":
    main()
