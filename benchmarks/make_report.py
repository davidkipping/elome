"""Render precision.json + speed.json into RESULTS.md."""

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))

with open(os.path.join(HERE, "precision.json")) as f:
    prec = json.load(f)
with open(os.path.join(HERE, "speed.json")) as f:
    speed = json.load(f)
prec_ecc = []
_pe = os.path.join(HERE, "precision_ecc.json")
if os.path.exists(_pe):
    with open(_pe) as f:
        prec_ecc = json.load(f)

def mem_mb(r):
    """Peak memory of one call above the process's level after importing
    the code (memwatch.py: the physical footprint, every code alike)."""
    return r.get("peak_mb")


lines = []
add = lines.append

add("<!-- GENERATED by benchmarks/make_report.py — edit that script, "
    "not this file -->\n")
add("# Elómë cross-code benchmark\n")
add("Machine: Apple M2 Max (12 CPU cores: 8P+4E; one 30-core GPU), "
    "macOS, MLX GPU fp32 / CPU fp64.\n")
add("Scenario: quadratic limb-darkened primary transit "
    "(P=3.456 d, a/R*=8.8, b=0.45, Rp/R*=0.1, u=[0.40, 0.25]), "
    "241-point precision grid, N-point speed sweeps. The eccentric "
    "sections repeat the comparison at e=0.3, w=63 deg with b held at "
    "0.45 at inferior conjunction.\n")

add("\n## Precision vs mpmath direct-integration oracle (30 digits)\n")
add("| code | max |err| | median |err| |")
add("|---|---:|---:|")
for r in sorted(prec, key=lambda r: r["max_err"]):
    add(f"| {r['code']} | {r['max_err']:.2e} | {r['median_err']:.2e} |")
add("\n`ellc` excluded: its PyPI wheel ships an x86_64-only binary "
    "(incompatible with arm64) and source builds need gfortran.\n")

if prec_ecc:
    add("\n## Precision, eccentric orbit (e = 0.3, w = 63 deg)\n")
    add("Every code solves Kepler's equation itself; the oracle's "
        "separation comes from an independent float64 Newton solver, so "
        "no code under test defines the geometry it is judged against.\n")
    add("| code | max |err| | median |err| |")
    add("|---|---:|---:|")
    for r in sorted(prec_ecc, key=lambda r: r["max_err"]):
        add(f"| {r['code']} | {r['max_err']:.2e} | {r['median_err']:.2e} |")

add("\n## Single light curve: wall time vs N (median)\n")
codes = sorted({(r["code"], r["threads"]) for r in speed
                if r["mode"] == "single" and "error" not in r})
ns = sorted({r["n"] for r in speed if r["mode"] == "single"})
add("| code (threads) | " + " | ".join(f"N={n:,}" for n in ns) + " |")
add("|---|" + "---:|" * len(ns))
for code, threads in codes:
    row = [f"{code} ({'all' if threads == 0 else threads})"]
    for n in ns:
        rec = next((r for r in speed if r["mode"] == "single"
                    and r["code"] == code and r["threads"] == threads
                    and r["n"] == n and "error" not in r), None)
        row.append("—" if rec is None else f"{rec['median_s']*1e3:,.2f} ms")
    add("| " + " | ".join(row) + " |")

if any(r["mode"] == "ecc" for r in speed):
    add("\n## Eccentric light curve: wall time vs N (median)\n")
    add("Orbit-inclusive: each code's own Kepler solver is inside the "
        "timed region.\n")
    codes_e = sorted({(r["code"], r["threads"]) for r in speed
                      if r["mode"] == "ecc" and "error" not in r})
    ns_e = sorted({r["n"] for r in speed if r["mode"] == "ecc"})
    add("| code (threads) | " + " | ".join(f"N={n:,}" for n in ns_e) + " |")
    add("|---|" + "---:|" * len(ns_e))
    for code, threads in codes_e:
        row = [f"{code} ({'all' if threads == 0 else threads})"]
        for n in ns_e:
            rec = next((r for r in speed if r["mode"] == "ecc"
                        and r["code"] == code and r["threads"] == threads
                        and r["n"] == n and "error" not in r), None)
            row.append("—" if rec is None
                       else f"{rec['median_s']*1e3:,.2f} ms")
        add("| " + " | ".join(row) + " |")

add("\n## Native batch: 512 parameter sets x 100,000 points\n")
add("| code | wall | curves/s | peak memory | notes |")
add("|---|---:|---:|---:|---|")
notes = {
    "elome_gpu": "fp32 GPU, one broadcast graph",
    "pytransit": "native parameter arrays (numba)",
    "jaxoplanet": "jax.vmap, CPU x64",
    "batman": "python loop (no native batch)",
    "exoplanet": "python loop (no native batch)",
}
for r in speed:
    if r["mode"] != "batch":
        continue
    if "error" in r:
        add(f"| {r['code']} | failed | — | — | {r['error'][:60]} |")
        continue
    m = mem_mb(r)
    add(f"| {r['code']} | {r['median_s']:.3f} s | "
        f"{512 / r['median_s']:,.0f} | "
        f"{'—' if m is None else f'{m:,.0f} MB'} | {notes.get(r['code'], '')} |")

grad = [r for r in speed if r["mode"] == "grad" and "error" not in r]
if grad:
    add("\n## Value + gradient of a scalar loss (single light curve)\n")
    add("sum(c * flux) for fixed random c, differentiated in rp, t0, period, "
        "a, b, u1 and u2. Only the differentiable codes.\n")
    gn = sorted({r["n"] for r in grad})
    add("| code | " + " | ".join(f"N={n:,}" for n in gn) + " |")
    add("|---|" + "---:|" * len(gn))
    for code in sorted({r["code"] for r in grad}):
        row = [code]
        for n in gn:
            rec = next((r for r in grad if r["code"] == code and r["n"] == n), None)
            row.append("—" if rec is None else f"{rec['median_s']*1e3:,.2f} ms")
        add("| " + " | ".join(row) + " |")

memrows = [r for r in speed if r["mode"] == "single" and "error" not in r
           and mem_mb(r) is not None]
if memrows:
    add("\n## Peak memory of one light curve\n")
    add("The process's physical footprint (what Activity Monitor shows), "
        "above its level after importing the code: what it holds to compute "
        "the light curve (arrays, compiled code, memory pools) and a call's "
        "transient peak (benchmarks/memwatch.py). One measure for every "
        "code, CPU and GPU (Metal) memory alike. Fewest threads per code.\n")
    mn = sorted({r["n"] for r in memrows})
    add("| code | " + " | ".join(f"N={n:,}" for n in mn) + " |")
    add("|---|" + "---:|" * len(mn))
    for code in sorted({r["code"] for r in memrows}):
        th = min(r["threads"] for r in memrows if r["code"] == code)
        row = [code]
        for n in mn:
            rec = next((r for r in memrows if r["code"] == code
                        and r["threads"] == th and r["n"] == n), None)
            row.append("—" if rec is None else f"{mem_mb(rec):,.1f} MB")
        add("| " + " | ".join(row) + " |")

bs_path = os.path.join(HERE, "batch_scaling.json")
if os.path.exists(bs_path):
    with open(bs_path) as f:
        bs = json.load(f)
    add("\n## Batch-size scaling (npv x 100,000 points): GPU vs its "
        "strongest CPU rival\n")
    add("| npv | Elómë GPU [curves/s] | PyTransit 12-core [curves/s] |")
    add("|---:|---:|---:|")
    npvs = sorted({r["npv"] for r in bs})
    for npv in npvs:
        row = [f"{npv}"]
        for code in ("elome_gpu", "pytransit"):
            rec = next((r for r in bs if r["npv"] == npv
                        and r["code"] == code and "median_s" in r), None)
            row.append("failed" if rec is None
                       else f"{npv / rec['median_s']:,.0f}")
        add("| " + " | ".join(row) + " |")
    add("\nWith the fused model-level Metal kernel (orbit + photometry in "
        "one register-resident pass, ~12 B/pt of memory traffic) the GPU "
        "streams ~55,000 curves/s flat to npv = 4096 with no memory "
        "cliff. PyTransit's numba batch streams ~1,950 curves/s at every "
        "size on 12 cores.\n")

_vjp = json.load(open(os.path.join(HERE, "vjp.json")))["median_ms"]
VJP_SENTENCE = (f"{_vjp['metal_value_grad']:.1f} ms vs "
                f"{_vjp['autodiff_value_grad'] / 1e3:.1f} s for reverse-mode autodiff at "
                f"1024 x 65,536 — a\n~{round(_vjp['autodiff_value_grad'] / _vjp['metal_value_grad'], -1):.0f}x spread")
add(f"""
## The eccentric comparison in one line

Every code above solves Kepler's equation inside the timed region. At
float64 Elómë ties exoplanet-core for the most accurate eccentric
light curve (4e-16 vs the independent mpmath oracle); at float32 on the
GPU it is the fastest past N ~ 1e5, reaching 15.3 ms at 10^7 points
against 207 ms for the next-fastest CPU code. Below ~10^4 points the
GPU dispatch floor dominates and the CPU codes win — the same crossover
documented for the circular case.

## What the speed tables do not show

Only Elómë and jaxoplanet are differentiable, and only Elómë
ships analytic gradients, fused into a Metal backward kernel: value+gradient
costs {VJP_SENTENCE} that is the number that matters for HMC sampling. batman,
PyTransit, exoplanet-core (numpy layer), and ellc provide no gradients.

## In-kernel exposure integration (512 chains x 5,000 points, M2 Max)

`flux_dev_from_tau` against the route it replaces —
`separation_circular` + `flux_dev_metal` + averaging the sub-exposure
axis outside the kernel. Reproduce: `python benchmarks/bench_tau_kernel.py`.

| route | evals/pt | forward | value+grad | peak MB (v+g) | max abs error |
|---|---:|---:|---:|---:|---:|
| expanded axis, n_sub=15 | 15 | 19.6 ms | 59.0 ms | 2776 | 1.6e-4 |
| in-kernel supersample, n_sub=15 | 15 | 6.8 ms | 15.5 ms | 51 | 1.6e-4 |
| in-kernel contact, n_gl=5 | 5-25 | 4.3 ms | 9.8 ms | 51 | 1.3e-7 |

Error is against an fp64 contact-rule reference at n_gl = 12 — neither of
the rules being compared, because scoring supersampling against a
supersampled reference flatters it. The middle row is the same arithmetic
as the first, so its 2.9x / 3.8x is purely the cost of materialising the
sub-exposure axis in MLX: every forward intermediate and every gradient
grid is n_sub times the light curve. The contact rule evaluates n_gl
nodes per non-empty piece of the exposure: 5 for an exposure no contact
falls inside, 25 only with all four inside.

At matched accuracy the gap is not a factor of three. Supersampling
converges as O(1/N) on a kinked curve, so 1e-6 needs n_sub ~ 2,271 —
which at 512 chains would ask for ~368 GB and page. Measured at 7 chains,
where both routes stay resident:

| matched to 1e-6 | forward | value+grad | peak MB |
|---|---:|---:|---:|
| expanded axis, n_sub=2271 | 36.7 ms | 120.7 ms | 1602 |
| in-kernel contact, n_gl=5 | 0.51 ms (**72x**) | 0.78 ms (**155x**) | 10 (**161-517x**) |

## The batching rule for samplers

Samplers must batch all walkers/chains into one model call — looping is
~three orders of magnitude slower. Rules, recipes, and reproducible
measurements: the docs' guide "Many parameter sets at once".

## Reading the scaling axes

* **CPU cores**: thread counts are honest core scaling for batman
  (OpenMP, if available) and PyTransit (numba). exoplanet-core is
  single-threaded by design; jaxoplanet (XLA) and MLX's CPU stream
  manage their own all-core pools and cannot be cleanly partitioned.
* **GPU cores**: Apple Silicon exposes one GPU whose cores cannot be
  partitioned from user space, so the N-sweep doubles as the GPU
  *saturation* curve — at small N most of the GPU's cores idle and
  latency dominates; throughput (points/s) rises with N until all
  cores saturate. True GPU-core scaling requires comparing chips
  (e.g. 30-core M2 Max vs 76-core M2 Ultra).
""")

out = os.path.join(HERE, "RESULTS.md")
with open(out, "w") as f:
    f.write("\n".join(lines))
