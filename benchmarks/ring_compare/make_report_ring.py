"""Render results_ring.json as RESULTS.md (generated -- edit this script)."""
import json
import os

from scenario_ring import (A_RS, B_IMPACT, BATCH_NPT, BATCH_NPV, N_PREC, PER,
                           RING_F, RING_IN, RING_OUT, RP, THETA_DEG, U1, U2,
                           W_LD)

HERE = os.path.dirname(os.path.abspath(__file__))
NAMES = {"elome_fp64": "Elómë fp64 (CPU)",
         "elome_fp32": "Elómë fp32 (GPU, Metal)",
         "pyppluss": "pyPplusS 0.1.5.3 (numpy, fp64; default order 5)",
         "pyppluss_n20": "pyPplusS 0.1.5.3 (order 20)",
         "squishyplanet": "squishyplanet 0.6.0 RingedSystem (JAX, fp64, CPU)",
         "jojo": "JoJo ring_lc (numpy, fp64)",
         "pryngles": "pryngles 1.0.2 RingedPlanet (numpy, 5000 + 5000 samples)"}


def ms(s):
    return f"{s * 1e3:,.2f} ms" if s < 10 else f"{s:,.1f} s"


def mem(r, mode, code, n=None):
    """Peak memory of one call above the process's level after importing
    the code (../memwatch.py: the physical footprint, every code alike)."""
    m = r.get("mem", {}).get(mode, {}).get(code)
    if m is not None and n is not None:
        m = m.get(str(n))
    if not m or "peak_mb" not in m:
        return "--"
    return f"{m['peak_mb']:,.0f} MB"


def main():
    r = json.load(open(os.path.join(HERE, "results_ring.json")))
    L = ["<!-- GENERATED by benchmarks/ring_compare/make_report_ring.py -->", "",
         "# Ringed planets: cross-code benchmark", "",
         f"Machine: {r['machine']}, Python {r['python']}; run {r['started']} "
         f"(load average {r['load'][0]:.1f} at the start). See README.md here "
         "for the environments.", "",
         f"Scenario: the spherical benchmark's transit (P = {PER} d, a/R* = {A_RS}, "
         f"b = {B_IMPACT}, Rp/R* = {RP}) with a flat ring from {RING_IN} to "
         f"{RING_OUT} Rp, |cos i_ring| = {1 - RING_F:.2f} (ring_f = {RING_F}) and "
         f"its long axis at {THETA_DEG:.0f} deg to the motion: the ring crosses "
         "the planet's disc. Limb darkening is the one profile every code "
         f"expresses exactly: I(mu) = 1 - {W_LD} (1 - mu^2), Elómë's hybrid2 "
         f"with its pole weight 0, pyPplusS's and pryngles' nonlinear law with "
         f"c4 alone, and the quadratic law (u1, u2) = ({U1}, {U2}) for "
         "squishyplanet and JoJo. Circular orbit, instantaneous fluxes. Every "
         "code's parameter mapping was checked against the reference before "
         "timing.", "",
         "## What each code covers", "",
         "| | Elómë | pyPplusS | squishyplanet | JoJo | pryngles |",
         "|---|---|---|---|---|---|",
         "| limb darkening | hybrid2/4/5 | nonlinear (4 coefficients), quadratic | polynomial, any order | quadratic | linear, quadratic, nonlinear |",
         "| ring opacity | optical depth | blocked fraction | opaque only | blocked fraction | optical depth |",
         "| planet | spherical or oblate | spherical | triaxial | spherical | spherical |",
         "| ring orientation | projected (ring_f, theta) | projected (inclination, rotation) | 3-D (obliquity, precession) | projected (f_r, obliquity) | 3-D, with the observer's direction |",
         "| input | orbit (circular, eccentric) or sky positions | sky positions | orbit | orbit | orbit |",
         "| method | Green's theorem, closed forms | polygon and segment areas, Gauss-Legendre over the limb darkening | Green's theorem, planet arcs by quadrature | Green's theorem, closed forms but the mu^1 term | point sampling (spangles) |",
         "| precision | fp64 (CPU), fp32 (GPU) | fp64 | fp64 | fp64 | fp64, sampling-limited |",
         "| exposures | contact rule, supersampling | none | oversampling | none | none |",
         "| gradients | analytic, every parameter | none | JAX | none | none |",
         "| many parameter sets | native batch | loop | jax.vmap | loop | loop |",
         "| extras | | (paper: any convex occultor) | | contact times | reflected light, shadows, polarisation, moons |", "",
         f"## Precision vs a float64 ray integral ({N_PREC} points)", "",
         "Against tests/ring_oracle.py (rays about the star's centre, adaptive "
         "to 1e-15), which shares no code with any code here.", "",
         "| code | opaque ring, max | translucent (tau = 0.6), max | nearly edge-on (ring_f = 0.95), max |",
         "|---|---:|---:|---:|"]
    p = {k: r.get(f"precision_{k}", {}) for k in ("opaque", "translucent", "edge")}
    for code in sorted(p["opaque"], key=lambda c: p["opaque"][c]["max"]):
        cells = []
        for k in ("opaque", "translucent", "edge"):
            v = p[k].get(code)
            cells.append(f"{v['max']:.2e}" if v else "opaque only" if code == "squishyplanet" else "--")
        L.append(f"| {NAMES[code]} | " + " | ".join(cells) + " |")
    L += ["", "## Single light curve: wall time vs N (median)", ""]
    ns = sorted({int(n) for v in r["single"].values() for n in v})
    L.append("| code | " + " | ".join(f"N = {n:,d}" for n in ns) + " |")
    L.append("|---|" + "---:|" * len(ns))
    for code, v in r["single"].items():
        L.append(f"| {NAMES[code]} | " + " | ".join(
            ms(v[str(n)]) if str(n) in v else "--" for n in ns) + " |")
    scaled = r.get("batch_scaled_from", {})
    L += ["", f"## Many parameter sets: {BATCH_NPV} sets x {BATCH_NPT:,d} points", "",
          "| code | wall | curves/s | peak memory | how |", "|---|---:|---:|---:|---|"]
    how = {"elome_fp32": "TransitModel.light_curves, one launch",
           "pyppluss": "Python loop (ring parameters are scalars per call)",
           "squishyplanet": "jax.jit(jax.vmap(lightcurve))",
           "jojo": "Python loop (no batch API)",
           "pryngles": "Python loop, a planet object per set"}
    for code, t in sorted(r["batch"].items(), key=lambda kv: kv[1]):
        note = how[code] + (f"; timed on {scaled[code]} sets, scaled" if code in scaled else "")
        L.append(f"| {NAMES[code]} | {ms(t)} | {BATCH_NPV / t:,.1f} | "
                 f"{mem(r, 'batch', code)} | {note} |")
    L += ["", "## Value + gradient of a scalar loss (single light curve)", "",
          "sum(c * flux) for fixed random c, in every parameter each code "
          "exposes: for Elómë rp, ring_in, ring_out, ring_f, theta, inc, t0, "
          "period, a and the limb-darkening weight. Only Elómë and "
          "squishyplanet are differentiable.", ""]
    gn = sorted({int(n) for v in r["grad"].values() for n in v})
    L.append("| code | " + " | ".join(f"N = {n:,d}" for n in gn) + " |")
    L.append("|---|" + "---:|" * len(gn))
    for code, v in r["grad"].items():
        L.append(f"| {NAMES[code]} | " + " | ".join(
            ms(v[str(n)]) if str(n) in v else "--" for n in gn) + " |")
    mn = sorted({int(n) for v in r.get("mem", {}).get("single", {}).values()
                 for n, m in v.items() if "peak_mb" in m})
    if mn:
        L += ["", "## Peak memory of one light curve", "",
              "The process's physical footprint (what Activity Monitor shows), "
              "above its level after importing the code: what it holds to "
              "compute the light curve (arrays, compiled code, memory pools) "
              "and a call's transient peak (../memwatch.py). One measure for "
              "every code, CPU and GPU (Metal) memory alike.", ""]
        L.append("| code | " + " | ".join(f"N = {n:,d}" for n in mn) + " |")
        L.append("|---|" + "---:|" * len(mn))
        for code in r["single"]:
            L.append(f"| {NAMES[code]} | " + " | ".join(
                mem(r, "single", code, n) for n in mn) + " |")
    L.append("")
    open(os.path.join(HERE, "RESULTS.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
